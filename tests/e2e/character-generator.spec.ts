import { test, expect } from '@playwright/test';

test('seven-part studio: seed, locks, editing, export and responsive preview', async ({page},info) => {
  const failures: string[]=[]; page.on('pageerror',error=>failures.push(error.message));
  await page.goto('/?view=character-generator');
  await expect(page).toHaveTitle('人物工坊 · hi-story');
  await expect(page.getByRole('heading',{name:'人物工坊'})).toBeVisible();
  await expect(page.locator('[data-slot]')).toHaveCount(7);
  await expect(page.getByRole('img',{name:/随机人物/})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  const seed=page.getByLabel('生成种子'),apply=page.getByRole('button',{name:'按种子生成'});
  await seed.fill('browser-fixture');await apply.click();
  const sprite=await page.locator('.character-sprite').innerHTML();
  const originalHair=await page.locator('#style-hair').inputValue();
  await page.getByRole('checkbox',{name:'锁定发型',exact:true}).check();
  await expect(page.getByRole('button',{name:'随机发型',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'随机一位旅人 ↻'}).click();
  await expect(page.locator('#style-hair')).toHaveValue(originalHair);
  await expect(page.locator('#style-hair')).toBeDisabled();
  await page.getByRole('checkbox',{name:'锁定发型',exact:true}).uncheck();
  await seed.fill('browser-fixture');await apply.click();
  expect(await page.locator('.character-sprite').innerHTML()).toBe(sprite);
  await page.locator('#style-hair').selectOption('mohawk');
  await expect(page.getByRole('img',{name:/莫霍克发/})).toBeVisible();
  await page.getByRole('button',{name:'发型颜色 2',exact:true}).click();
  await expect(page.getByRole('button',{name:'发型颜色 2',exact:true})).toHaveAttribute('aria-pressed','true');
  const pants=await page.locator('#style-pants').inputValue();
  await page.getByRole('button',{name:'随机上衣',exact:true}).click();
  await expect(page.locator('#style-pants')).toHaveValue(pants);
  await expect(page.locator('#style-hair')).toHaveValue('mohawk');
  await seed.fill(' ');await apply.click();
  await expect(page.getByRole('status')).toContainText('不能全为空白');
  const downloading=page.waitForEvent('download');await page.getByRole('button',{name:'导出人物 JSON ↓'}).click();
  const download=await downloading;expect(download.suggestedFilename()).toBe('hi-story-character.json');
  const stream=await download.createReadStream();const chunks:Buffer[]=[];for await(const chunk of stream!)chunks.push(chunk);
  const model=JSON.parse(Buffer.concat(chunks).toString());
  expect(Object.keys(model.parts)).toHaveLength(7);expect(model.parts.hair).toEqual({styleId:'mohawk',color:'#614436'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:`test-results/character-generator-${info.project.name}.png`,fullPage:true});
  await page.getByRole('link',{name:'返回旅程 ↗'}).click();
  await expect(page.getByRole('heading',{name:'雾桥递信'})).toBeVisible();
  await page.getByRole('link',{name:'打开人物工坊 ↗'}).click();
  await expect(page.getByRole('heading',{name:'人物工坊'})).toBeVisible();
  expect(failures).toEqual([]);
});
